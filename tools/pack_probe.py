#!/usr/bin/env python3
"""Embed an audited Mach-O image unchanged in a HAP's signed ELF code section."""
import argparse
from pathlib import Path
from prepare_ipa import make_probe

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("image", type=Path)
parser.add_argument("assembly", type=Path)
args = parser.parse_args()
image = args.image.resolve()
if image.read_bytes() != make_probe():
    raise SystemExit("Only the standalone return-42 Mach-O is executable in this milestone")
path = str(image).replace("\\", "\\\\").replace('"', '\\"')
args.assembly.write_text(f'''// Generated by tools/pack_probe.py. Preserve the original Mach-O bytes.
.section .text.hm_guest,"ax",%progbits
.p2align 14
.global hm_packaged_probe_image
.hidden hm_packaged_probe_image
.type hm_packaged_probe_image,%object
hm_packaged_probe_image:
.incbin "{path}"
.size hm_packaged_probe_image, .-hm_packaged_probe_image
.section .note.GNU-stack,"",%progbits
''')
